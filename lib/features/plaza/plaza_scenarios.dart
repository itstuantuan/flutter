import 'dart:math';

class PlazaLine {
  const PlazaLine(this.speaker, this.text);
  final String speaker, text;
}

class PlazaScenario {
  const PlazaScenario(this.title, this.script);
  final String title, script;
  List<PlazaLine> get lines => script
      .trim()
      .split('\n')
      .map((line) {
        final split = line.indexOf('：');
    return split < 0 || line.startsWith('✦')
            ? PlazaLine('', line)
            : PlazaLine(line.substring(0, split), line.substring(split + 1));
      })
      .toList(growable: false);
}

// Shuffle bags give every story a turn without repeating at a bag boundary.
class PlazaScenarioPicker {
  PlazaScenarioPicker({Random? random}) : _random = random ?? Random();
  final Random _random;
  final List<PlazaScenario> _bag = [];
  PlazaScenario? _last;
  PlazaScenario next() {
    if (_bag.isEmpty) {
      _bag.addAll(plazaScenarios);
      _bag.shuffle(_random);
      if (_bag.last == _last) {
        final first = _bag.first;
        _bag[0] = _bag.last;
        _bag[_bag.length - 1] = first;
      }
    }
    return _last = _bag.removeLast();
  }
}

