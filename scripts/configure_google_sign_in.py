#!/usr/bin/env python3
"""Generate iOS Google URL scheme from the same JSON used by --dart-define.

Only public OAuth client IDs are read. API secrets are never copied or printed.
Missing Google configuration keeps phone login usable.
"""
import argparse
import json
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]
CLIENT_ID = re.compile(r"^[a-zA-Z0-9-]+\.apps\.googleusercontent\.com$")


def render(config):
    ios_id = config.get("GOOGLE_IOS_CLIENT_ID", "")
    server_id = config.get("GOOGLE_SERVER_CLIENT_ID", "")
    for name, value in [("GOOGLE_IOS_CLIENT_ID", ios_id), ("GOOGLE_SERVER_CLIENT_ID", server_id)]:
        if not isinstance(value, str) or (value and not CLIENT_ID.fullmatch(value)):
            raise ValueError(f"{name} must be an OAuth client ID ending in .apps.googleusercontent.com")
    scheme = ".".join(reversed(ios_id.split("."))) if ios_id else "com.viitor.bots.google-unconfigured"
    return ("// Generated by scripts/configure_google_sign_in.py. Do not edit.\n"
            f"GOOGLE_REVERSED_CLIENT_ID = {scheme}\n")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--config", required=True, type=Path)
    parser.add_argument("--output", type=Path, default=ROOT / "ios/Flutter/GoogleSignIn.local.xcconfig")
    args = parser.parse_args()
    try:
        config = json.loads(args.config.read_text())
        content = render(config)
        args.output.parent.mkdir(parents=True, exist_ok=True)
        temp = args.output.with_suffix(".tmp")
        temp.write_text(content)
        temp.replace(args.output)
    except (OSError, ValueError) as error:
        # Do not echo invalid JSON lines, which could contain API credentials.
        parser.exit(1, f"Google configuration failed ({type(error).__name__}); check file and OAuth Client ID format.\n")
    configured = bool(config.get("GOOGLE_IOS_CLIENT_ID") and config.get("GOOGLE_SERVER_CLIENT_ID"))
    print("Google iOS callback configured." if configured else
          "Google OAuth configuration incomplete; phone login remains available.")


if __name__ == "__main__":
    main()
